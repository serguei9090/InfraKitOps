/**
 * Content model + static reference data for the Cheatsheets & Documentation
 * Hub (spec Module 5). No React imports here — this file is data only,
 * rendered by a future `src/adapters/ui/tools/CheatsheetsScreen.tsx`.
 *
 * Everything below is static/const on purpose: the app is client-first and
 * offline, so cheatsheet content ships in the bundle instead of being
 * fetched over the network.
 */

/**
 * A single reference row: a command/pattern/key on the left, what it does,
 * and a short worked example of using it.
 */
export interface CheatsheetEntry {
  /**
   * The command, regex token, sysctl key, cron field/shortcut, or octal
   * digit being documented. Rendered in a monospace font by the UI.
   */
  command: string
  /** Plain-language explanation of what it does. */
  description: string
  /** Short worked example (an invocation, a matched string, a config line). */
  example: string
}

/** A titled group of related `entries` within a `CheatsheetPage`. */
export interface CheatsheetSection {
  title: string
  entries: CheatsheetEntry[]
}

/** One full cheatsheet, e.g. "Git Commands" or "Chmod Permissions". */
export interface CheatsheetPage {
  /**
   * Stable slug for the currently-selected-page UI state — independent of
   * `title` so a copy edit never breaks the "which page was open" state.
   */
  id: string
  title: string
  /** One-line summary shown under the page title. */
  description: string
  sections: CheatsheetSection[]
}

/**
 * What kind of thing an external resource actually is. This matters because
 * "official docs for a project" (documentation), "a GitHub repo that is
 * itself just a curated list of other links" (curatedList), "a hands-on
 * practice/exercise repo" (exercise), and "a structured learning path"
 * (roadmap) serve very different purposes even though they're all just a
 * name + URL on the surface.
 *
 * The `ai*` / `mcpServer` / `automation` / `catalog` / `devService` values
 * back the Knowledge Hub's "AI & Automation" group (see
 * KNOWLEDGE_HUB_AI_EXPANSION_PLAN.md):
 * - catalog     — a directory/aggregator of many tools (AI tool indexes, model rankings)
 * - mcpServer   — MCP servers, gateways, registries
 * - aiFramework — agent / AI-dev frameworks & SDKs
 * - aiApp       — end-user AI software / agents / products
 * - aiSkill     — agent-skill ecosystems, SKILL.md, skill marketplaces
 * - automation  — automation platforms & workflow engines
 * - aiModel     — a foundation model plus its official tooling / harness
 * - devService  — hosted infra products: tunnels, static hosts, PaaS, deploy platforms
 */
export type ResourceType =
  | 'documentation'
  | 'curatedList'
  | 'exercise'
  | 'roadmap'
  | 'catalog'
  | 'mcpServer'
  | 'aiFramework'
  | 'aiApp'
  | 'aiSkill'
  | 'automation'
  | 'aiModel'
  | 'devService'

